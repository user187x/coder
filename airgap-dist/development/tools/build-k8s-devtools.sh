#!/usr/bin/env bash
# Builds development/workspace-image/packages/k8s-devtools_<VERSION>_amd64.deb: a self-contained package of the
# developer's own Kubernetes tools, so workspaces have them without any network:
#   - k9s: the exact custom binary (not a rebuild) and its configuration - config.yaml, aliases.yaml, plugins (with the
#     k9s-copy-secret script) and skins; per-machine state (clusters/, screen-dumps/, benchmarks/, backups) is left
#     out. /usr/bin/k9s gives users without a k9s configuration the bundled one on first run, then runs k9s;
#   - kubectl: the exact binary;
#   - kubelogin (int128/kubelogin, the release binary, pinned by its checksum) as the kubectl plugin
#     kubectl-oidc_login: the kubeconfig the template writes for admins signs them in with Keycloak's device login;
#   - bash completion for k9s and kubectl.
# The .deb is committed (packages/SHA256SUMS pins it), so the workspace image (build-workspace-image.sh) can be
# rebuilt from a clone; it carries it into the delivery bundle.
#   ./build-k8s-devtools.sh [VERSION]      default 1.1.0
# Sources (environment): K9S_BIN (~/.local/bin/k9s), K9S_CONFIG (~/.config/k9s), KUBECTL_BIN (on PATH),
# KUBELOGIN_BIN (default: the pinned release, downloaded once into ~/.cache/coder-airgapped).
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"; dev="$(dirname "$here")"
version="${1:-1.1.0}"; pkg=k8s-devtools
k9s_bin="${K9S_BIN:-$HOME/.local/bin/k9s}"; k9s_config="${K9S_CONFIG:-$HOME/.config/k9s}"
kubectl_bin="${KUBECTL_BIN:-$(command -v kubectl)}"
kubelogin_version=v1.36.4
kubelogin_zip_sha256=9e8baeb4905d35a301304af2548324997add512fe94ab20e65993d167212bf85
out="${dev}/workspace-image/packages"; deb="${out}/${pkg}_${version}_amd64.deb"

if [[ -z "${KUBELOGIN_BIN:-}" ]]; then
	cache="${XDG_CACHE_HOME:-$HOME/.cache}/coder-airgapped/kubelogin-${kubelogin_version}"
	KUBELOGIN_BIN="${cache}/kubelogin"
	if [[ ! -x "$KUBELOGIN_BIN" ]]; then
		mkdir -p "$cache"
		curl -fsSL -o "${cache}/kubelogin_linux_amd64.zip" \
			"https://github.com/int128/kubelogin/releases/download/${kubelogin_version}/kubelogin_linux_amd64.zip"
		echo "${kubelogin_zip_sha256}  ${cache}/kubelogin_linux_amd64.zip" | sha256sum -c --quiet \
			|| { rm -f "${cache}/kubelogin_linux_amd64.zip"; echo "ERROR: kubelogin checksum mismatch" >&2; exit 1; }
		unzip -o -q "${cache}/kubelogin_linux_amd64.zip" kubelogin -d "$cache"
	fi
fi
kubelogin_bin="$KUBELOGIN_BIN"

for f in "$k9s_bin" "$kubectl_bin" "$kubelogin_bin"; do
	[[ -x "$f" ]] || { echo "ERROR: not an executable: $f" >&2; exit 1; }
	file -L "$f" | grep -q 'ELF 64-bit.*x86-64' || { echo "ERROR: not a linux/amd64 binary: $f" >&2; exit 1; }
done
for f in config.yaml aliases.yaml plugins skins; do
	[[ -e "${k9s_config}/${f}" ]] || { echo "ERROR: missing ${k9s_config}/${f}" >&2; exit 1; }
done

root="$(mktemp -d)"; trap 'rm -rf "$root"' EXIT
lib="${root}/usr/lib/${pkg}"; share="${root}/usr/share/${pkg}"; doc="${root}/usr/share/doc/${pkg}"
comp="${root}/usr/share/bash-completion/completions"
mkdir -p "$lib" "${share}/k9s" "$doc" "$comp" "${root}/usr/bin" "${root}/DEBIAN"

# The binaries, exactly as they are (-L: through symlinks).
install -m 0755 "$(readlink -f "$k9s_bin")" "${lib}/k9s"
install -m 0755 "$(readlink -f "$kubectl_bin")" "${root}/usr/bin/kubectl"
install -m 0755 "$(readlink -f "$kubelogin_bin")" "${lib}/kubelogin"
ln -s "../lib/${pkg}/kubelogin" "${root}/usr/bin/kubectl-oidc_login"
ln -s "../lib/${pkg}/kubelogin" "${root}/usr/bin/kubelogin"

# k9s's configuration (symlinks resolved), and its plugin script on PATH (the plugin looks there first).
for f in config.yaml aliases.yaml plugins skins; do cp -rL "${k9s_config}/${f}" "${share}/k9s/"; done
find "${share}/k9s" -type d -exec chmod 0755 {} + ; find "${share}/k9s" -type f -exec chmod 0644 {} +
find "${share}/k9s/plugins" -path '*/scripts/*' -type f -exec chmod 0755 {} +
if [[ -f "${share}/k9s/plugins/scripts/k9s-copy-secret" ]]; then
	ln -s "../share/${pkg}/k9s/plugins/scripts/k9s-copy-secret" "${root}/usr/bin/k9s-copy-secret"
fi

cat >"${root}/usr/bin/k9s" <<'EOF'
#!/bin/sh
# k9s (package k8s-devtools): users without a k9s configuration get the bundled one (settings, aliases, plugins,
# skins) on first run; an existing configuration is never touched. Then the bundled k9s binary runs.
dir="${K9S_CONFIG_DIR:-${XDG_CONFIG_HOME:-$HOME/.config}/k9s}"
if [ -n "$HOME" ] && [ ! -e "$dir/config.yaml" ]; then
	mkdir -p "$dir" && cp -R /usr/share/k8s-devtools/k9s/. "$dir/" 2>/dev/null || true
fi
exec /usr/lib/k8s-devtools/k9s "$@"
EOF
chmod 0755 "${root}/usr/bin/k9s"

# Bash completion, generated by the binaries themselves.
"${lib}/k9s" completion bash >"${comp}/k9s" 2>/dev/null || rm -f "${comp}/k9s"
"${root}/usr/bin/kubectl" completion bash >"${comp}/kubectl"

k9s_v="$("${lib}/k9s" version -s 2>/dev/null | awk '/^Version/ {print $2}')"
k9s_c="$("${lib}/k9s" version -s 2>/dev/null | awk '/^Commit/ {print $2}')"
k9s_d="$("${lib}/k9s" version -s 2>/dev/null | awk '/^Date/ {print $2}')"
kubectl_v="$("${root}/usr/bin/kubectl" version --client 2>/dev/null | awk '/^Client Version/ {print $3}')"
kubelogin_v="$("${lib}/kubelogin" --version 2>/dev/null | awk '{print $3}')"
cat >"${doc}/README" <<EOF
k8s-devtools ${version}: Kubernetes tools for workspaces, packaged from a developer's own machine.

  k9s       ${k9s_v} (commit ${k9s_c}, built ${k9s_d})  /usr/bin/k9s -> /usr/lib/${pkg}/k9s
            sha256 $(sha256sum "${lib}/k9s" | cut -d' ' -f1)
            configuration: /usr/share/${pkg}/k9s (copied into ~/.config/k9s on first run when there is none)
  kubectl   ${kubectl_v}  /usr/bin/kubectl
            sha256 $(sha256sum "${root}/usr/bin/kubectl" | cut -d' ' -f1)
  kubelogin ${kubelogin_v}  /usr/bin/kubectl-oidc_login (kubectl oidc-login), /usr/bin/kubelogin
            -> /usr/lib/${pkg}/kubelogin, sha256 $(sha256sum "${lib}/kubelogin" | cut -d' ' -f1)

kubectl and k9s need a cluster to talk to: a kubeconfig in ~/.kube/config (or KUBECONFIG).
EOF
cat >"${doc}/copyright" <<'EOF'
k9s (https://github.com/derailed/k9s), kubectl (https://github.com/kubernetes/kubernetes) and kubelogin
(https://github.com/int128/kubelogin) are licensed under the Apache License 2.0
(/usr/share/common-licenses/Apache-2.0). The k9s binary carries local patches.
EOF

installed_kb="$(du -sk "$root" --exclude=DEBIAN | cut -f1)"
cat >"${root}/DEBIAN/control" <<EOF
Package: ${pkg}
Version: ${version}
Section: admin
Priority: optional
Architecture: amd64
Maintainer: coder-airgapped platform <root@localhost>
Installed-Size: ${installed_kb}
Depends: libc6
Recommends: jq, fzf, bash-completion
Provides: k9s, kubectl, kubelogin
Conflicts: k9s, k9s-patched, kubectl, kubelogin
Replaces: k9s, k9s-patched, kubectl, kubelogin
Homepage: https://k9scli.io
Description: k9s (custom build, with its configuration), kubectl and kubelogin
 Self-contained: a developer's own k9s ${k9s_v} binary and configuration (settings, aliases, plugins, skins)
 and kubectl ${kubectl_v}, with bash completion, and kubelogin ${kubelogin_v} (kubectl oidc-login).
 k9s gives users without a k9s
 configuration the bundled one on first run.
EOF

mkdir -p "$out"; rm -f "${out}/${pkg}"_*_amd64.deb
fakeroot dpkg-deb -Zxz --build "$root" "$deb" >/dev/null
(cd "$out" && sha256sum ./*.deb | sed 's|  \./|  |' >SHA256SUMS)
echo "built ${deb} ($(du -h "$deb" | cut -f1)): k9s ${k9s_v}, kubectl ${kubectl_v}, kubelogin ${kubelogin_v}"
