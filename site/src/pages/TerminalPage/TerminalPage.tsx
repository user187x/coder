import { useCallback, useEffect, useMemo, useRef, useState } from "react";
import { useQuery } from "react-query";
import { useNavigate, useParams, useSearchParams } from "react-router";
import { deploymentConfig } from "#/api/queries/deployment";
import { appearanceSettings } from "#/api/queries/users";
import {
	workspaceByOwnerAndName,
	workspaceUsage,
} from "#/api/queries/workspaces";
import { Button } from "#/components/Button/Button";
import { useProxy } from "#/contexts/ProxyContext";
import { ThemeOverride } from "#/contexts/ThemeProvider";
import { useEmbeddedMetadata } from "#/hooks/useEmbeddedMetadata";
import { TERMINAL_EXITED } from "#/modules/platform/agentPanels/terminalExited";
import {
	getTerminalConfig,
	terminalRenderer,
} from "#/modules/terminal/terminalConfig";
import type { ConnectionStatus } from "#/modules/terminal/types";
import {
	WorkspaceTerminal,
	type WorkspaceTerminalHandle,
} from "#/modules/terminal/WorkspaceTerminal";
import { WorkspaceTerminalAlerts } from "#/modules/terminal/WorkspaceTerminalAlerts";
import themes from "#/theme";
import { pageTitle } from "#/utils/page";
import { openMaybePortForwardedURL } from "#/utils/portForward";
import { generateConnectionSessionId, generateUUID } from "#/utils/random";
import { getMatchingAgentOrFirst } from "#/utils/workspace";
import { TerminalCommandConsentDialog } from "./TerminalCommandConsentDialog";

const TerminalPage: React.FC = () => {
	// Maybe one day we'll support a light themed terminal, but terminal coloring
	// is notably a pain because of assumptions certain programs might make about
	// your background color.
	const theme = themes.dark;
	const navigate = useNavigate();
	const { proxy, proxyLatencies } = useProxy();
	const params = useParams() as { username: string; workspace: string };
	const username = params.username.replace("@", "");
	const terminalRef = useRef<WorkspaceTerminalHandle>(null);
	const [connectionStatus, setConnectionStatus] =
		useState<ConnectionStatus>("initializing");
	const [commandConfirmed, setCommandConfirmed] = useState(false);
	// Platform: the shell exited. The window closes; one the browser keeps open (not opened by a script) says so. In a
	// dashboard panel (a frame) or popped out of one (a window it opened), the panel is told: it rolls up and starts
	// over, as the Terminal drop-down does (TERMINAL_EXITED, AccordionPanel).
	const [ended, setEnded] = useState(false);
	const endSession = useCallback(() => {
		for (const host of [window.parent, window.opener as Window | null]) {
			if (host && host !== window) {
				try {
					host.postMessage({ type: TERMINAL_EXITED }, window.location.origin);
				} catch {
					// another origin: nothing to tell
				}
			}
		}
		window.close();
		window.setTimeout(() => {
			if (!window.closed) {
				setEnded(true);
			}
		}, 300);
	}, []);
	const [searchParams] = useSearchParams();
	const isDebugging = searchParams.has("debug");
	// The reconnection token is a unique token that identifies
	// a terminal session. It's generated by the client to reduce
	// a round-trip, and must be a UUIDv4.
	const reconnectionToken = searchParams.get("reconnect") ?? generateUUID();
	// The session ID correlates all logs and requests for this
	// terminal session. Unlike the reconnection token, it is not persisted in
	// the URL: a new page load (including a reload) is a new session.
	const [sessionId] = useState(() => generateConnectionSessionId());
	const command = searchParams.get("command") || undefined;
	const appSlug = searchParams.get("app") || undefined;
	const containerName = searchParams.get("container") || undefined;
	const containerUser = searchParams.get("container_user") || undefined;

	// The workspace name is in the format:
	// <workspace name>[.<agent name>]
	const workspaceNameParts = params.workspace?.split(".");
	const workspace = useQuery(
		workspaceByOwnerAndName(username, workspaceNameParts?.[0]),
	);
	const workspaceAgent = workspace.data
		? getMatchingAgentOrFirst(workspace.data, workspaceNameParts?.[1])
		: undefined;

	// Resolve the ?app= slug to a command from the agent's app list.
	// These commands are admin-configured in the template and trusted,
	// so they skip the confirmation dialog.
	const appCommand = useMemo(() => {
		if (!appSlug || !workspaceAgent) {
			return undefined;
		}
		const app = workspaceAgent.apps.find((a) => a.slug === appSlug);
		return app?.command || undefined;
	}, [appSlug, workspaceAgent]);

	// Raw ?command= params require explicit user confirmation.
	// Trusted ?app= commands bypass the dialog.
	const commandPendingConfirmation = !!command && !appSlug && !commandConfirmed;
	const initialCommand = appCommand
		? appCommand
		: command && commandConfirmed
			? command
			: undefined;
	const selectedProxy = proxy.proxy;
	const latency = selectedProxy ? proxyLatencies[selectedProxy.id] : undefined;

	const config = useQuery(deploymentConfig());

	// Periodically report workspace usage.
	useQuery(
		workspaceUsage({
			usageApp: "reconnecting-pty",
			connectionStatus,
			workspaceId: workspace.data?.id,
			agentId: workspaceAgent?.id,
		}),
	);

	const handleWebLink = useCallback(
		(uri: string) => {
			openMaybePortForwardedURL(
				uri,
				proxy.preferredWildcardHostname,
				workspaceAgent?.name,
				workspace.data?.name,
				username,
			);
		},
		[workspaceAgent, workspace.data, username, proxy.preferredWildcardHostname],
	);
	const handleTerminalError = useCallback(
		(error: Error) => {
			console.error("WebSocket failed:", {
				client_session_id: sessionId,
				error,
			});
		},
		[sessionId],
	);

	const { metadata } = useEmbeddedMetadata();
	const appearanceSettingsQuery = useQuery(
		appearanceSettings(metadata.userAppearance),
	);
	const terminalConfig = getTerminalConfig(
		config.data,
		appearanceSettingsQuery.data,
		proxy.preferredPathAppURL,
	);
	// Platform: Ghostty's terminal where the template gives it in place of the web terminal (DATAFLOW)
	const renderer = terminalRenderer(
		terminalConfig.renderer,
		workspaceAgent,
		searchParams.get("renderer"),
	);
	const terminalErrorMessage =
		workspace.error instanceof Error
			? `Unable to fetch workspace: ${workspace.error.message}`
			: !workspace.isLoading && !workspaceAgent
				? "Unable to fetch workspace agent: no agent found with ID, is the workspace started?"
				: undefined;

	// Updates the reconnection token into the URL if necessary.
	useEffect(() => {
		if (searchParams.get("reconnect") === reconnectionToken) {
			return;
		}
		searchParams.set("reconnect", reconnectionToken);
		navigate(
			{
				search: searchParams.toString(),
			},
			{
				replace: true,
			},
		);
	}, [navigate, reconnectionToken, searchParams]);

	return (
		<ThemeOverride theme={theme}>
			{workspace.data && (
				<title>
					{pageTitle(
						renderer === "ghostty" ? "Ghostty" : "Terminal",
						`${workspace.data.owner_name}/${workspace.data.name}`,
					)}
				</title>
			)}

			<div
				className="relative flex flex-col h-screen"
				data-status={connectionStatus}
			>
				{ended && (
					// Platform: the session ended and the browser kept the window: no reconnect into a new shell.
					<div
						className="absolute inset-0 z-10 flex flex-col items-center justify-center gap-4 bg-surface-primary/90 text-content-primary"
						data-testid="terminal-ended"
						role="status"
					>
						<p className="m-0 text-base">This terminal session has ended.</p>
						<div className="flex gap-2">
							<Button onClick={() => window.close()}>Close window</Button>
							<Button
								variant="outline"
								onClick={() => {
									searchParams.delete("reconnect");
									window.location.search = searchParams.toString();
								}}
							>
								New session
							</Button>
						</div>
					</div>
				)}
				<WorkspaceTerminalAlerts
					agent={workspaceAgent}
					status={connectionStatus}
					onAlertChange={() => {
						terminalRef.current?.refit();
					}}
				/>
				<WorkspaceTerminal
					ref={terminalRef}
					agentId={workspaceAgent?.id}
					operatingSystem={workspaceAgent?.operating_system}
					initialCommand={initialCommand}
					containerName={containerName}
					containerUser={containerUser}
					onStatusChange={setConnectionStatus}
					onExit={endSession}
					onError={handleTerminalError}
					reconnectionToken={reconnectionToken}
					sessionId={sessionId}
					baseUrl={terminalConfig.baseUrl}
					terminalFontFamily={terminalConfig.fontFamily}
					renderer={renderer}
					onOpenLink={handleWebLink}
					loading={
						workspace.isLoading ||
						config.isLoading ||
						appearanceSettingsQuery.isLoading ||
						commandPendingConfirmation
					}
					errorMessage={terminalErrorMessage}
					testId="terminal"
				/>
			</div>

			{latency && isDebugging && (
				<span className="absolute bottom-6 right-6 text-content-disabled text-sm">
					Latency: {latency.latencyMS.toFixed(0)}ms{" "}
				</span>
			)}

			{command && !appSlug && (
				<TerminalCommandConsentDialog
					open={!commandConfirmed}
					command={command}
					onConfirm={() => {
						setCommandConfirmed(true);
					}}
					onDeny={() => {
						window.close();
					}}
				/>
			)}
		</ThemeOverride>
	);
};

export default TerminalPage;
